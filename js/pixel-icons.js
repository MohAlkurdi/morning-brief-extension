export function pxIcon(name, cls = '') {
  const rows = ICONS[name] ?? ICONS.spark;
  const NS = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', '0 0 9 9');
  svg.setAttribute('class', `px-icon ${cls}`.trim());
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('shape-rendering', 'crispEdges');
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) {
      const r = document.createElementNS(NS, 'rect');
      r.setAttribute('x', m.index); r.setAttribute('y', y); r.setAttribute('width', m[0].length); r.setAttribute('height', 1);
      svg.append(r);
    }
  });
  return svg;
}
