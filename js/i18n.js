export const LANGS = { en: 'English', ar: 'العربية' };
let lang = 'en';

export function setLang(l) {
  lang = STRINGS[l] ? l : 'en';
  if (globalThis.document) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }
  return lang;
}

export const getLang = () => lang;
export const isRtl = () => lang === 'ar';

export function t(key, vars = {}, l = lang) {
  const s = STRINGS[l]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Gregorian calendar and Western digits in both languages, so dates match the times the AI writes.
export const locale = (l = lang) => (l === 'ar' ? 'ar-u-ca-gregory-nu-latn' : undefined);

// Splits a translated string on {placeholders} and drops DOM nodes in, so word order can change per language.
export function tn(key, nodes = {}, vars = {}) {
  const raw = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return raw.split(/\{(\w+)\}/).map((part, i) => (i % 2 ? nodes[part] ?? vars[part] ?? '' : part)).filter(p => p !== '');
}

